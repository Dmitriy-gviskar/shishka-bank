const roman = (n) => ['', 'I', 'II', 'III', 'IV', 'V', 'VI', 'VII'][n] || String(n);
const ach = [];
for (const [metric, key, steps] of TRACKS) {
  steps.forEach(([t, title, reward], i) => {
    ach.push({
      code: `${key}_${i + 1}`,
      title,
      desc: `${title} — достигни ${t} (${metric})`,
      metric, threshold: t, tier: Math.min(i + 1, 3), reward,
      track: key, level: i + 1, track_title: `${steps[0][1]}`.split(' ')[0], roman: roman(i + 1),
    });
  });
}
// оставляем только поля схемы + track/level для UI-группировки
